"""Read-only IG M1 path coverage for an immutable recorded market decision.

This is an evidence inventory, not a training label or trading signal. Historical
market_decisions may have been generated by rejected M15 proxy models.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from hashlib import sha256
import json
from typing import Callable

import pandas as pd


INVENTORY_POLICY_VERSION = "RECORDED_DECISION_IG_M1_FULL_PATH_60M_V1"
QUOTE_KEYS = ("bid_open", "bid_high", "bid_low", "bid_close",
              "ask_open", "ask_high", "ask_low", "ask_close")


@dataclass(frozen=True)
class RecordedDecision:
    decision_id: str
    market: str
    generated_at_utc: datetime
    candle_open_utc: datetime | None
    candle_timeframe: str | None
    model_version_id: str | None
    decision: str
    executable: bool

    def __post_init__(self) -> None:
        if (not self.decision_id or not self.market or
                self.generated_at_utc.tzinfo is None or
                self.generated_at_utc.utcoffset() != timedelta(0) or
                self.decision not in {"BUY", "SELL", "HOLD"}):
            raise ValueError("Invalid recorded decision evidence")
        if self.candle_open_utc is not None and (
                self.candle_open_utc.tzinfo is None or
                self.candle_open_utc.utcoffset() != timedelta(0)):
            raise ValueError("Candle timestamp must be UTC")


def recorded_identity(decision: RecordedDecision) -> str:
    return sha256(json.dumps({**decision.__dict__,
                              "inventory_policy_version": INVENTORY_POLICY_VERSION},
                             sort_keys=True, separators=(",", ":"),
                             default=str).encode()).hexdigest()


def assess_recorded_path(
    decision: RecordedDecision, candles: pd.DataFrame, *,
    regular_session: Callable[[datetime], bool], now_utc: datetime,
    horizon_minutes: int = 60,
    duplicate_timestamps: set[pd.Timestamp] | None = None,
) -> dict[str, object]:
    """Require each broker-native completed M1 minute from eligible open.

    Every recorded decision is included, including HOLD and governance-rejected
    BUY/SELL. Coverage is not a counterfactual trade return or a model label.
    """
    if (horizon_minutes < 1 or now_utc.tzinfo is None or
            now_utc.utcoffset() != timedelta(0)):
        raise ValueError("Invalid inventory horizon or current UTC")
    eligible = pd.Timestamp(decision.generated_at_utc).ceil("min")
    last = eligible + pd.Timedelta(horizon_minutes - 1, unit="min")
    base = {"recorded_decision_id": decision.decision_id,
            "inventory_prediction_id": recorded_identity(decision),
            "market": decision.market, "decision": decision.decision,
            "decision_generated_at_utc": decision.generated_at_utc.isoformat(),
            "source_candle_open_utc": decision.candle_open_utc.isoformat()
                if decision.candle_open_utc else None,
            "source_candle_timeframe": decision.candle_timeframe,
            "source_model_version_id": decision.model_version_id,
            "recorded_executable": decision.executable,
            "inventory_policy_version": INVENTORY_POLICY_VERSION,
            "eligible_entry_at_utc": eligible.isoformat(),
            "required_last_m1_open_utc": last.isoformat(),
            "required_m1_minutes": horizon_minutes,
            "status": "UNVERIFIABLE", "reason": None,
            "complete_m1_minutes": 0, "first_missing_m1_utc": None,
            "source_ig_m1_path_sha256": None,
            "label_authority": "NONE_COVERAGE_ONLY"}
    if last + pd.Timedelta(1, unit="min") > pd.Timestamp(now_utc):
        return {**base, "reason": "HORIZON_NOT_YET_COMPLETE"}
    if (candles.index.tz is None or not candles.index.is_unique or
            not set(QUOTE_KEYS + ("source", "completed", "quality_status")).issubset(candles.columns)):
        return {**base, "reason": "M1_FRAME_SCHEMA_INVALID"}
    selected = candles.sort_index().loc[eligible:last]
    by_time = {at: row for at, row in selected.iterrows()}
    complete = 0
    path_refs = []
    for minute in range(horizon_minutes):
        at = eligible + pd.Timedelta(minute, unit="min")
        if not regular_session(at.to_pydatetime()):
            return {**base, "reason": "SESSION_BOUNDARY_IN_PATH",
                    "complete_m1_minutes": complete,
                    "first_missing_m1_utc": at.isoformat()}
        if at in (duplicate_timestamps or set()):
            return {**base, "reason": "DUPLICATE_IG_M1_TIMESTAMP",
                    "complete_m1_minutes": complete,
                    "first_missing_m1_utc": at.isoformat()}
        row = by_time.get(at)
        if row is None:
            return {**base, "reason": "IG_M1_MISSING",
                    "complete_m1_minutes": complete,
                    "first_missing_m1_utc": at.isoformat()}
        if not _valid(row):
            return {**base, "reason": "IG_M1_INVALID_OR_NONBROKER",
                    "complete_m1_minutes": complete,
                    "first_missing_m1_utc": at.isoformat()}
        path_refs.append({"open_time_utc": at.isoformat(),
                          "candle_id": int(row.candle_id) if "candle_id" in row
                              and pd.notna(row.candle_id) else None,
                          "source": str(row.source),
                          "quotes": {key: float(row[key]) for key in QUOTE_KEYS}})
        complete += 1
    return {**base, "status": "COMPLETE_IG_M1_PATH", "reason": None,
            "complete_m1_minutes": complete,
            "source_ig_m1_path_sha256": sha256(json.dumps(path_refs, sort_keys=True,
                separators=(",", ":")).encode()).hexdigest(),
            "first_missing_m1_utc": None}


def _valid(row: pd.Series) -> bool:
    if (not str(row.source).startswith("IG_LIGHTSTREAMER") or
            not bool(row.completed) or row.quality_status != "PASS"):
        return False
    try:
        values = {key: float(row[key]) for key in QUOTE_KEYS}
    except (ValueError, TypeError, KeyError):
        return False
    import math
    if any(not math.isfinite(value) or value <= 0 for value in values.values()):
        return False
    for side in ("bid", "ask"):
        if (values[f"{side}_low"] > min(values[f"{side}_open"], values[f"{side}_close"])
                or values[f"{side}_high"] < max(values[f"{side}_open"], values[f"{side}_close"])
                or values[f"{side}_high"] < values[f"{side}_low"]):
            return False
    return (values["ask_open"] > values["bid_open"] and
            values["ask_close"] > values["bid_close"])
